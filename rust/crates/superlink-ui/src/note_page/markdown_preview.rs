//! CommonMark preview model. HTML and image references remain local text;
//! rendering a note never fetches remote resources.
use super::*;
use gpui::{HighlightStyle, StyledText};
use pulldown_cmark::{Event, Options, Parser, Tag, TagEnd};
use std::ops::Range;

#[derive(Clone, Default, PartialEq)]
struct Inline {
    bold: bool,
    italic: bool,
    strike: bool,
    code: bool,
    link: bool,
}
impl Inline {
    fn highlight(&self, theme: Theme) -> HighlightStyle {
        HighlightStyle {
            font_weight: self.bold.then_some(FontWeight::BOLD),
            font_style: self.italic.then_some(gpui::FontStyle::Italic),
            background_color: self.code.then_some(theme.button),
            color: self.link.then_some(theme.accent),
            strikethrough: self.strike.then_some(gpui::StrikethroughStyle {
                thickness: px(1.),
                color: Some(theme.text),
            }),
            underline: self.link.then_some(gpui::UnderlineStyle {
                thickness: px(1.),
                color: Some(theme.accent),
                wavy: false,
            }),
            ..Default::default()
        }
    }
}
#[derive(Default)]
enum Kind {
    #[default]
    Root,
    Paragraph,
    Heading(u8),
    Quote,
    List(Option<u64>),
    Item(String),
    Code,
    Table,
    Row(bool),
    Cell,
}
#[derive(Default)]
struct Block {
    kind: Kind,
    children: Vec<Block>,
    text: String,
    spans: Vec<(Range<usize>, Inline)>,
}
impl Block {
    fn append(&mut self, text: &str, style: &Inline) {
        let start = self.text.len();
        self.text.push_str(text);
        self.spans.push((start..self.text.len(), style.clone()));
    }
    fn render(self, theme: Theme) -> AnyElement {
        let has_text = !self.text.is_empty();
        let text = StyledText::new(self.text).with_highlights(
            self.spans
                .into_iter()
                .map(|(range, style)| (range, style.highlight(theme))),
        );
        // Text is emitted before nested blocks, as generated by CommonMark.
        let mut content = div().flex().flex_col().min_w(px(0.)).text_color(theme.text);
        if has_text {
            content = content.child(text);
        }
        content = content.children(self.children.into_iter().map(|child| child.render(theme)));
        match self.kind {
            Kind::Heading(level) => content
                .text_size(px(match level {
                    1 => 32.,
                    2 => 26.,
                    3 => 22.,
                    _ => 18.,
                }))
                .font_weight(FontWeight::BOLD)
                .mt_3()
                .mb_2()
                .into_any_element(),
            Kind::Quote => content
                .pl_3()
                .border_l_2()
                .border_color(theme.border)
                .text_color(theme.muted)
                .my_2()
                .into_any_element(),
            Kind::Code => content
                .p_3()
                .bg(theme.button)
                .rounded_md()
                .font_family("Menlo")
                .text_size(px(12.))
                .my_2()
                .into_any_element(),
            Kind::Item(marker) => div()
                .flex()
                .gap_2()
                .pl_2()
                .child(marker)
                .child(content.flex_1())
                .into_any_element(),
            Kind::Table => content
                .border_1()
                .border_color(theme.border)
                .my_2()
                .into_any_element(),
            Kind::Row(header) => {
                // Cells keep a bounded equal share of the available width.
                let row = content
                    .flex_row()
                    .w_full()
                    .border_b_1()
                    .border_color(theme.border);
                if header {
                    row.font_weight(FontWeight::BOLD)
                        .bg(theme.button)
                        .into_any_element()
                } else {
                    row.into_any_element()
                }
            }
            Kind::Cell => content
                .flex_1()
                .p_2()
                .border_r_1()
                .border_color(theme.border)
                .into_any_element(),
            Kind::Paragraph => content.mb_2().into_any_element(),
            _ => content.into_any_element(),
        }
    }
}

fn finish(stack: &mut Vec<Block>) {
    if stack.len() > 1 {
        let block = stack.pop().unwrap();
        stack.last_mut().unwrap().children.push(block);
    }
}
fn document(body: &str) -> Vec<Block> {
    let mut stack = vec![Block::default()];
    let mut style = Inline::default();
    let mut styles = Vec::new();
    for event in Parser::new_ext(
        body,
        Options::ENABLE_STRIKETHROUGH | Options::ENABLE_TABLES | Options::ENABLE_TASKLISTS,
    ) {
        match event {
            Event::Start(tag) => {
                let kind = match tag {
                    Tag::Paragraph => Some(Kind::Paragraph),
                    Tag::Heading { level, .. } => Some(Kind::Heading(level as u8)),
                    Tag::BlockQuote(_) => Some(Kind::Quote),
                    Tag::CodeBlock(_) => Some(Kind::Code),
                    Tag::List(first) => Some(Kind::List(first)),
                    Tag::Item => {
                        let marker = stack
                            .iter_mut()
                            .rev()
                            .find_map(|block| match &mut block.kind {
                                Kind::List(Some(next)) => {
                                    let marker = format!("{next}.");
                                    *next = next.saturating_add(1);
                                    Some(marker)
                                }
                                Kind::List(None) => Some("•".into()),
                                _ => None,
                            })
                            .unwrap_or_default();
                        Some(Kind::Item(marker))
                    }
                    Tag::Table(_) => Some(Kind::Table),
                    Tag::TableHead => Some(Kind::Row(true)),
                    Tag::TableRow => Some(Kind::Row(false)),
                    Tag::TableCell => Some(Kind::Cell),
                    Tag::Strong | Tag::Emphasis | Tag::Strikethrough | Tag::Link { .. } => {
                        styles.push(style.clone());
                        match tag {
                            Tag::Strong => style.bold = true,
                            Tag::Emphasis => style.italic = true,
                            Tag::Strikethrough => style.strike = true,
                            Tag::Link { .. } => style.link = true,
                            _ => {}
                        }
                        None
                    }
                    _ => None,
                };
                if let Some(kind) = kind {
                    let parent = stack.last_mut().unwrap();
                    if !parent.text.is_empty() {
                        parent.children.push(Block {
                            kind: Kind::Paragraph,
                            text: std::mem::take(&mut parent.text),
                            spans: std::mem::take(&mut parent.spans),
                            children: Vec::new(),
                        });
                    }
                    stack.push(Block {
                        kind,
                        ..Default::default()
                    });
                }
            }
            Event::End(tag) => match tag {
                TagEnd::Strong | TagEnd::Emphasis | TagEnd::Strikethrough | TagEnd::Link => {
                    style = styles.pop().unwrap_or_default()
                }
                TagEnd::Paragraph
                | TagEnd::Heading(_)
                | TagEnd::BlockQuote(_)
                | TagEnd::CodeBlock
                | TagEnd::List(_)
                | TagEnd::Item
                | TagEnd::Table
                | TagEnd::TableHead
                | TagEnd::TableRow
                | TagEnd::TableCell => finish(&mut stack),
                _ => {}
            },
            Event::Text(text) | Event::Html(text) | Event::InlineHtml(text) => {
                stack.last_mut().unwrap().append(&text, &style)
            }
            Event::Code(text) => {
                let mut code = style.clone();
                code.code = true;
                stack.last_mut().unwrap().append(&text, &code);
            }
            Event::SoftBreak | Event::HardBreak => stack.last_mut().unwrap().append("\n", &style),
            Event::Rule => stack.last_mut().unwrap().children.push(Block {
                text: "────────────────────".into(),
                ..Default::default()
            }),
            Event::TaskListMarker(checked) => stack
                .last_mut()
                .unwrap()
                .append(if checked { "☑ " } else { "☐ " }, &style),
            _ => {}
        }
    }
    while stack.len() > 1 {
        finish(&mut stack);
    }
    let root = stack.pop().unwrap();
    if root.text.is_empty() {
        root.children
    } else {
        vec![root]
    }
}
pub(crate) fn markdown_blocks(body: &str, theme: Theme) -> Vec<AnyElement> {
    document(body)
        .into_iter()
        .take(10_000)
        .map(|block| block.render(theme))
        .collect()
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn preserves_nested_styles_lists_tables_code_and_literal_underscores() {
        let blocks = document(
            "# 标题\n\nfoo_bar ***组合*** `**原样**`\n\n1. 第一项\n2. 第二项\n\n| 字段 | 值 |\n|---|---|\n| a | b |\n\n```sql\nselect 1;\n```\n",
        );
        assert!(matches!(blocks[0].kind, Kind::Heading(1)));
        assert_eq!(blocks[1].text, "foo_bar 组合 **原样**");
        assert!(
            blocks[1]
                .spans
                .iter()
                .any(|(_, style)| style.bold && style.italic)
        );
        assert!(matches!(blocks[2].children[1].kind, Kind::Item(ref n) if n == "2."));
        assert!(matches!(blocks[3].kind, Kind::Table));
        assert_eq!(blocks[3].children[1].children[1].text, "b");
        assert!(matches!(blocks[4].kind, Kind::Code));
        assert_eq!(blocks[4].text, "select 1;\n");
    }
}

//! Visual table creation from designer fields.

use crate::error::{SqlError, SqlResult};
use crate::identifier::{object_name, quote_identifier, structure_dialect, text_literal};
use crate::model::{ColumnDefinition, Object};
use crate::structure_column::column_definition;

/// True when the dialect has a structured designer.
pub fn can_create_table(dialect: &str) -> bool {
    !structure_dialect(dialect).is_empty()
}

/// Builds a bounded, validated definition from designer fields.
pub fn build_create_table(
    dialect: &str,
    object: &Object,
    columns: &[ColumnDefinition],
) -> SqlResult<String> {
    let kind = structure_dialect(dialect);
    if kind.is_empty() {
        return Err(SqlError::new("此数据库暂不支持可视化建表"));
    }
    if object.name.trim().is_empty() || columns.is_empty() || columns.len() > 1024 {
        return Err(SqlError::new("请填写表名和 1–1024 个字段"));
    }
    let table = object_name(dialect, object)?;
    let mut primary: Vec<String> = Vec::new();
    let mut seen: Vec<String> = Vec::new();
    for column in columns {
        if column.name.trim().is_empty() || seen.contains(&column.name.to_lowercase()) {
            return Err(SqlError::new(format!(
                "字段名称不能为空或重复：{}",
                column.name
            )));
        }
        seen.push(column.name.to_lowercase());
        if !column.key.is_empty() && column.key != "PRI" {
            return Err(SqlError::new("仅支持主键，请在建表后添加其他索引"));
        }
        if column.key == "PRI" {
            primary.push(quote_identifier(dialect, &column.name)?);
        }
    }
    let mut definitions: Vec<String> = Vec::new();
    let mut comments: Vec<String> = Vec::new();
    let mut auto_count = 0usize;
    let mut inline_primary = false;
    for column in columns {
        let extra = column.extra.trim().to_lowercase();
        if !extra.is_empty() && extra != "auto_increment" {
            return Err(SqlError::new(format!("不支持的字段属性：{}", column.name)));
        }
        let auto = extra == "auto_increment";
        if auto {
            auto_count += 1;
            let data_type = column.data_type.trim().to_uppercase();
            let integer = matches!(
                data_type.as_str(),
                "INT" | "INTEGER" | "BIGINT" | "SMALLINT"
            ) || (kind == "mysql"
                && matches!(
                    data_type.as_str(),
                    "TINYINT" | "MEDIUMINT" | "INT UNSIGNED" | "BIGINT UNSIGNED"
                ));
            if !integer || column.key != "PRI" || primary.len() != 1 || column.has_default {
                return Err(SqlError::new(format!(
                    "自增字段必须为整数类型、单列主键且没有默认值：{}",
                    column.name
                )));
            }
            if kind == "sqlite" && data_type != "INTEGER" {
                return Err(SqlError::new("SQLite 自增主键必须使用 INTEGER 类型"));
            }
        }
        let mut current = column.clone();
        if current.key == "PRI" {
            current.nullable = "NO".into();
        }
        let mut definition = column_definition(kind, &current, &ColumnDefinition::default())
            .map_err(|error| SqlError::new(format!("字段 {}：{}", column.name, error)))?;
        if auto && kind == "postgres" {
            definition.push_str(" GENERATED BY DEFAULT AS IDENTITY");
        }
        if auto && kind == "sqlite" {
            definition.push_str(" PRIMARY KEY AUTOINCREMENT");
            inline_primary = true;
        }
        if !column.comment.is_empty() && kind == "postgres" {
            let quoted = quote_identifier(dialect, &column.name).unwrap_or_default();
            comments.push(format!(
                "COMMENT ON COLUMN {table}.{quoted} IS {};",
                text_literal(kind, &column.comment)
            ));
        }
        if !column.comment.is_empty() && kind == "sqlite" {
            return Err(SqlError::new(format!(
                "SQLite 不支持字段注释，请清空注释：{}",
                column.name
            )));
        }
        definitions.push(definition);
    }
    if auto_count > 1 {
        return Err(SqlError::new("只能设置一个自增字段"));
    }
    if !primary.is_empty() && !inline_primary {
        definitions.push(format!("PRIMARY KEY ({})", primary.join(", ")));
    }
    let mut sql = format!(
        "CREATE TABLE {table} (\n  {}\n);",
        definitions.join(",\n  ")
    );
    if !comments.is_empty() {
        sql.push('\n');
        sql.push_str(&comments.join("\n"));
    }
    Ok(sql)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn auto_increment_column() -> ColumnDefinition {
        ColumnDefinition {
            name: "id".into(),
            data_type: "INTEGER".into(),
            nullable: "NO".into(),
            key: "PRI".into(),
            extra: "auto_increment".into(),
            ..Default::default()
        }
    }

    #[test]
    fn emits_dialect_specific_definitions() {
        for (dialect, fragment) in [
            ("mysql", "AUTO_INCREMENT"),
            ("postgres", "GENERATED BY DEFAULT AS IDENTITY"),
            ("sqlite", "PRIMARY KEY AUTOINCREMENT"),
        ] {
            let columns = [
                auto_increment_column(),
                ColumnDefinition {
                    name: "value".into(),
                    data_type: "TEXT".into(),
                    nullable: "YES".into(),
                    ..Default::default()
                },
            ];
            let object = Object {
                name: "order.details".into(),
                scope: "demo".into(),
                ..Default::default()
            };
            let sql = build_create_table(dialect, &object, &columns).unwrap();
            assert!(sql.contains(fragment), "{dialect}: {sql}");
            assert_eq!(sql.matches("PRIMARY KEY").count(), 1, "{sql}");
            if dialect == "mysql" {
                assert!(sql.contains("\x60demo\x60.\x60order.details\x60"), "{sql}");
            }
        }
    }

    #[test]
    fn quotes_schema_and_comments() {
        let columns = [ColumnDefinition {
            name: "v".into(),
            data_type: "TEXT".into(),
            nullable: "YES".into(),
            comment: "it's useful".into(),
            ..Default::default()
        }];
        let object = Object {
            name: "t".into(),
            schema: "literal.schema".into(),
            ..Default::default()
        };
        let sql = build_create_table("postgres", &object, &columns).unwrap();
        assert!(sql.contains("\"literal.schema\".\"t\""), "{sql}");
        assert!(sql.contains("'it''s useful'"), "{sql}");
    }

    #[test]
    fn rejects_invalid_definitions() {
        let base = ColumnDefinition {
            name: "id".into(),
            data_type: "INTEGER".into(),
            nullable: "NO".into(),
            key: "PRI".into(),
            ..Default::default()
        };
        let edits: Vec<Box<dyn Fn(&mut ColumnDefinition)>> = vec![
            Box::new(|column| column.name = " ".into()),
            Box::new(|column| column.data_type = "INT); DROP TABLE x; --".into()),
            Box::new(|column| column.extra = "generated".into()),
            Box::new(|column| {
                column.extra = "auto_increment".into();
                column.data_type = "TEXT".into();
            }),
            Box::new(|column| {
                column.default = Some("1; DROP TABLE x".into());
                column.has_default = true;
            }),
        ];
        for edit in edits {
            let mut column = base.clone();
            edit(&mut column);
            let object = Object {
                name: "t".into(),
                ..Default::default()
            };
            assert!(
                build_create_table("mysql", &object, &[column.clone()]).is_err(),
                "{column:?}"
            );
        }
        let object = Object {
            name: "t".into(),
            ..Default::default()
        };
        assert!(build_create_table("mysql", &object, &[]).is_err());
        assert!(build_create_table("mysql", &object, &[base.clone(), base.clone()]).is_err());
        assert!(!can_create_table("redis"));
        assert!(can_create_table("mariadb"));
    }
}
